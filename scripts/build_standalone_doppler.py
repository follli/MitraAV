def body(path: str, drop_imports: bool = True) -> str:
    text = (SRC / path).read_text(encoding="utf-8")
    lines = [ln for ln in text.splitlines() if not ln.startswith(("from __future__", "from ."))]
    return "\n".join(lines).strip() + "\n"


def only_function(path: str, name: str) -> str:
    text = (SRC / path).read_text(encoding="utf-8")
    m = re.search(rf"^def {name}\(.*?(?=^def |\Z)", text, re.S | re.M)
    return m.group(0).rstrip() + "\n"


